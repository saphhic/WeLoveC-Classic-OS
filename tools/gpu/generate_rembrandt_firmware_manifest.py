#!/usr/bin/env python3
"""Generate a hash-pinned C++ manifest from local Yellow Carp firmware files."""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys
from pathlib import Path


MAX_FIRMWARE_SIZE = 64 * 1024 * 1024
FIRMWARE_FILES = (
    "yellow_carp_toc.bin",
    "yellow_carp_ta.bin",
    "yellow_carp_asd.bin",
    "yellow_carp_pfp.bin",
    "yellow_carp_me.bin",
    "yellow_carp_ce.bin",
    "yellow_carp_mec.bin",
    "yellow_carp_mec2.bin",
    "yellow_carp_rlc.bin",
    "yellow_carp_sdma.bin",
    "yellow_carp_dmcub.bin",
)
OPTIONAL_FIRMWARE_FILES = ("yellow_carp_vcn.bin",)
VFS_COMPONENT_RE = re.compile(r"^[A-Za-z0-9_.-]+$")


def validate_vfs_prefix(value: str) -> str:
    if not value.startswith("/") or "\\" in value:
        raise argparse.ArgumentTypeError(
            "VFS prefix must be an absolute POSIX path"
        )
    components = [component for component in value.split("/") if component]
    if any(component in (".", "..") for component in components):
        raise argparse.ArgumentTypeError("VFS prefix cannot contain dot components")
    if any(not VFS_COMPONENT_RE.fullmatch(component) for component in components):
        raise argparse.ArgumentTypeError(
            "VFS prefix contains an unsupported character"
        )
    return "/" + "/".join(components) if components else "/"


def hash_file(path: Path) -> tuple[int, bytes]:
    digest = hashlib.sha256()
    size = 0
    with path.open("rb") as stream:
        before = os.fstat(stream.fileno())
        while True:
            chunk = stream.read(1024 * 1024)
            if not chunk:
                break
            size += len(chunk)
            if size > MAX_FIRMWARE_SIZE:
                raise ValueError(f"{path}: exceeds {MAX_FIRMWARE_SIZE} bytes")
            digest.update(chunk)
        after = os.fstat(stream.fileno())
    if (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns) != (
        after.st_dev,
        after.st_ino,
        after.st_size,
        after.st_mtime_ns,
    ) or size != after.st_size:
        raise ValueError(f"{path}: changed while it was being hashed")
    if size == 0:
        raise ValueError(f"{path}: empty firmware file")
    return size, digest.digest()


def render_manifest(
    required_entries: list[tuple[str, int, bytes]],
    optional_entries: list[tuple[str, int, bytes]],
) -> str:
    lines = [
        "// Generated by tools/gpu/generate_rembrandt_firmware_manifest.py.",
        "// Review the firmware source and hashes before compiling this file.",
        "#pragma once",
        "",
        '#include "../gpu_firmware.hpp"',
        "",
        "namespace welovec::display::gpu {",
        "",
    ]
    lines.append(
        "static constexpr FirmwareManifestEntry kRembrandtFirmwareManifest[] = {"
    )
    for path, size, digest in required_entries + optional_entries:
        digest_text = ", ".join(f"0x{byte:02x}" for byte in digest)
        lines.append(f'    {{"{path}", {size}u, {{{digest_text}}}}},')
    lines.extend(
        [
            "};",
            "",
            "static constexpr uint32_t kRembrandtRequiredFirmwareCount =",
            f"    {len(required_entries)}u;",
            "static constexpr uint32_t kRembrandtFirmwareManifestCount =",
            "    static_cast<uint32_t>(sizeof(kRembrandtFirmwareManifest) /",
            "                           sizeof(kRembrandtFirmwareManifest[0]));",
            "",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "firmware_dir",
        type=Path,
        help="local linux-firmware amdgpu directory containing Yellow Carp blobs",
    )
    parser.add_argument(
        "--vfs-prefix",
        required=True,
        type=validate_vfs_prefix,
        help="absolute VFS directory where the generated paths will be loaded",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="write the generated C++ header here (default: stdout)",
    )
    args = parser.parse_args()

    if not args.firmware_dir.is_dir():
        parser.error(f"firmware directory does not exist: {args.firmware_dir}")

    required_entries: list[tuple[str, int, bytes]] = []
    optional_entries: list[tuple[str, int, bytes]] = []
    try:
        for filename in FIRMWARE_FILES:
            path = args.firmware_dir / filename
            if not path.is_file():
                raise ValueError(f"required firmware file is missing: {path}")
            size, digest = hash_file(path)
            vfs_path = f"{args.vfs_prefix.rstrip('/')}/amdgpu/{filename}"
            if not vfs_path.startswith("/"):
                vfs_path = "/" + vfs_path
            required_entries.append((vfs_path, size, digest))
        for filename in OPTIONAL_FIRMWARE_FILES:
            path = args.firmware_dir / filename
            if not path.is_file():
                continue
            size, digest = hash_file(path)
            vfs_path = f"{args.vfs_prefix.rstrip('/')}/amdgpu/{filename}"
            if not vfs_path.startswith("/"):
                vfs_path = "/" + vfs_path
            optional_entries.append((vfs_path, size, digest))
    except (OSError, ValueError) as error:
        print(f"manifest generation failed: {error}", file=sys.stderr)
        return 1

    output = render_manifest(required_entries, optional_entries)
    if args.output:
        try:
            with args.output.open("w", encoding="utf-8", newline="\n") as stream:
                stream.write(output)
        except OSError as error:
            print(f"cannot write {args.output}: {error}", file=sys.stderr)
            return 1
    else:
        sys.stdout.write(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
